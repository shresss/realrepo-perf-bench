#!/bin/sh
# Coordinator08:23 source-only installation, identical portable generated version.
set -eu
archive=$1
source_root=$2
case "$source_root" in /app|/tests/pristine) ;; *) exit 2 ;; esac
test ! -e "$source_root"
mkdir -p "$source_root"
tar -xzf "$archive" --strip-components=1 -C "$source_root"
python - "$source_root" <<'AQ_METADATA'
from pathlib import Path
import sys,sysconfig
root=Path(sys.argv[1])
(root/'statsmodels/_version.py').write_bytes(b'# file generated by setuptools-scm\n# don\'t change, don\'t track in version control\n\n__all__ = ["__version__", "__version_tuple__", "version", "version_tuple"]\n\nTYPE_CHECKING = False\nif TYPE_CHECKING:\n    from typing import Tuple\n    from typing import Union\n\n    VERSION_TUPLE = Tuple[Union[int, str], ...]\nelse:\n    VERSION_TUPLE = object\n\nversion: str\n__version__: str\n__version_tuple__: VERSION_TUPLE\nversion_tuple: VERSION_TUPLE\n\n__version__ = version = \'0.15.0.dev0\'\n__version_tuple__ = version_tuple = (0, 15, 0, \'dev0\')\n    ')
site=Path(sysconfig.get_paths()['purelib'])
(site/'statsmodels-source.pth').write_text(str(root)+'\n')
metadata=site/'statsmodels-0.15.0.dev0.dist-info'
metadata.mkdir(exist_ok=False)
(metadata/'METADATA').write_text('Metadata-Version: 2.1\nName: statsmodels\nVersion: 0.15.0.dev0\n')
(metadata/'top_level.txt').write_text('statsmodels\n')
AQ_METADATA
